// backend/controllers/chat.controller.js
import { GoogleGenAI } from "@google/genai";
import PDFDocument from "pdfkit";
import chatModel from "../models/chat.model.js";
import jwt from "jsonwebtoken";
import config from "../config/config.js";

const genAI = new GoogleGenAI({ apiKey: process.env.GEMINI_API_KEY });

function getUserId(req) {
    const authorization = req.headers.authorization;
    const token = authorization?.startsWith("Bearer ") ? authorization.slice(7) : null;

    if (!token) {
        const error = new Error("Authentication token is required");
        error.statusCode = 401;
        throw error;
    }

    try {
        return jwt.verify(token, config.JWT_SECRET).id;
    } catch {
        const error = new Error("Invalid or expired authentication token");
        error.statusCode = 401;
        throw error;
    }
}

export async function getChatHistory(req, res) {
    try {
        const userId = getUserId(req);
        const history = await chatModel.find({ user: userId })
            .select("_id title updatedAt")
            .sort({ updatedAt: -1 })
            .lean();

        return res.status(200).json({ success: true, data: history });
    } catch (error) {
        return res.status(error.statusCode || 500).json({
            success: false,
            message: error.statusCode ? error.message : "Unable to load chat history"
        });
    }
}

export async function generateNotes(req, res) {
    try {
        const userId = getUserId(req);
        const prompt = req.body.prompt?.trim();

        if (!prompt) {
            return res.status(400).json({ success: false, message: "Prompt is required" });
        }

        const systemInstruction = "You are aiExamNotesGenerator, an expert tutor for a BSc IT student. Provide structured, accurate, and concise exam notes with code examples where applicable.";
        const result = await genAI.models.generateContent({
            model: "gemini-3.8-flash",
            contents: `${systemInstruction}\n\nStudent request: ${prompt}`,
        });
        const aiResponseText = result.text?.trim();

        if (!aiResponseText) {
            throw new Error("Gemini returned an empty response");
        }

        const chat = await chatModel.create({
            user: userId,
            title: prompt.slice(0, 80),
            messages: [
                { role: "user", content: prompt },
                { role: "ai", content: aiResponseText }
            ]
        });

        // 4. Send the response back to React
        return res.status(200).json({
            success: true,
            message: aiResponseText,
            chatId: chat._id
        });

    } catch (error) {
        console.error("Gemini API Error:", error.message);
        const providerMessage = error.message || "Failed to generate AI response.";
        return res.status(error.statusCode || 500).json({
            success: false,
            message: error.statusCode ? error.message : providerMessage
        });
    }
}

export function downloadPdf(req, res) {
    try {
        getUserId(req);
        const title = req.body.title?.trim() || "AI Exam Notes";
        const content = req.body.content?.trim();

        if (!content) {
            return res.status(400).json({ success: false, message: "Response content is required" });
        }

        const safeFilename = `${title.replace(/[^a-z0-9]+/gi, "-").replace(/(^-|-$)/g, "").slice(0, 60) || "ai-exam-notes"}.pdf`;
        const document = new PDFDocument({ margin: 54, size: "A4" });

        res.setHeader("Content-Type", "application/pdf");
        res.setHeader("Content-Disposition", `attachment; filename="${safeFilename}"`);
        document.pipe(res);
        document.fontSize(20).fillColor("#111827").text(title, { underline: false });
        document.moveDown(0.5);
        document.fontSize(9).fillColor("#6b7280").text("Generated by aiExamNotesGenerator");
        document.moveDown(1.5);
        document.fontSize(11).fillColor("#1f2937").text(content, {
            align: "left",
            lineGap: 4,
        });
        document.end();
    } catch (error) {
        if (!res.headersSent) {
            return res.status(error.statusCode || 500).json({
                success: false,
                message: error.statusCode ? error.message : "Unable to create PDF"
            });
        }
    }
}
